# -*- coding: utf-8 -*-
"""生成 out/report_v2.md：规则、各档国家名单、人口统计。"""
import csv
import json
import os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(BASE, "data")
OUT = os.path.join(BASE, "out")
WORLD_POP = 8161972574

ORDER = ["后工业化国家", "成熟工业化国家", "工业化中后期国家", "工业化中期国家",
         "工业化起步国家", "准备工业化国家"]

# 中文国名：取自 NE geojson 的 NAME_ZH（ADM0_A3 → 中文名）
with open(os.path.join(BASE, "raw", "ne_110m_countries.geojson"), encoding="utf-8") as f:
    gj = json.load(f)
ZH = {ft["properties"].get("ADM0_A3"): ft["properties"].get("NAME_ZH")
      for ft in gj["features"] if ft["properties"].get("NAME_ZH")}
ZH["SDS"] = ZH.get("SSD")  # 南苏丹别名
ZH.update({"ISR": "以色列", "TWN": "台湾"})

rows = []
with open(os.path.join(DATA, "final_v2.csv"), encoding="utf-8-sig") as f:
    for r in csv.DictReader(f):
        rows.append(r)

lines = ["# 全球工业化阶段地图（V2）— 结果报告", "",
         "产出图：`out/world_industrial_stage_map_v2.png`；数据：`data/final_v2.csv`（96国）", "",
         "## 一、分类规则", "",
         "- 记分：得分 = 人均年发电量 ÷ 标准人均发电量 + 人均年钢产量 ÷ 标准人均钢产量；**得分 > 2 视为达标**。",
         "- 阶段标准（人均发电量 / 人均钢产量）：成熟工业化 4000 kWh / 400 kg；工业化中后期 3000 kWh / 300 kg；工业化中期 1000 kWh / 100 kg；工业化起步 500 kWh / 50 kg。",
         "- 归类：发达国家（IMF发达经济体口径）→ 后工业化国家（以色列、台湾地区按此列入）；其余国家从高标准到低标准依次对照，取所能达到的最高阶段；四档均未达 → 准备工业化国家。",
         "- 中国按记分归入成熟工业化国家（成熟档得分 3.55 > 2）；台湾地区在 IMF 发达经济体名单内，列入后工业化国家（2026-09-23 用户更正）。",
         "- 人口1000万及以上国家参与分类（共95国）；以色列按发达国家列入（UN WPP2024人口938.7万，以色列官方口径已超1000万），合计96个实体。", "",
         "## 二、各档国家名单（括号内依次为：成熟档/中后期档/中期档/起步档得分）", ""]

tot = 0.0
for c in ORDER:
    sub = [r for r in rows if r["category"] == c]
    p = sum(float(r["pop2024"]) for r in sub)
    tot += p
    lines.append(f"### {c}（{len(sub)}国，{p/1e8:.2f}亿，占全球 {p/WORLD_POP*100:.2f}%）")
    lines.append("")
    for r in sorted(sub, key=lambda x: -float(x["pop2024"])):
        nm = ZH.get(r["code"]) or r["entity"]
        lines.append(f"- {nm}（{float(r['pop2024'])/1e6:.1f}M，人均电{float(r['pc_elec_kwh']):.0f} kWh，"
                     f"人均钢{float(r['pc_steel_kg']):.1f} kg，得分 {float(r['s_mature']):.2f}/{float(r['s_late']):.2f}/"
                     f"{float(r['s_mid']):.2f}/{float(r['s_start']):.2f}）")
    lines.append("")

uncls = WORLD_POP - tot
lines += ["## 三、人口统计（2024年）", "",
          "| 类别 | 国家数 | 总人口 | 占全球总人口比重 |", "|---|---:|---:|---:|"]
for c in ORDER:
    sub = [r for r in rows if r["category"] == c]
    p = sum(float(r["pop2024"]) for r in sub)
    lines.append(f"| {c} | {len(sub)} | {p/1e8:.2f}亿 | {p/WORLD_POP*100:.1f}% |")
lines += [f"| 其他人口不足1000万国家 | — | {uncls/1e8:.2f}亿 | {uncls/WORLD_POP*100:.1f}% |",
          f"| **全球合计** | **{len(rows)}** | **{WORLD_POP/1e8:.2f}亿** | **100.0%** |", "",
          "## 四、临界国家（某档得分 2.0±0.2）", "",
          "- 成熟档边界：土耳其 2.03、马来西亚 2.03（入选）；伊朗 1.94、哈萨克斯坦 1.95（未入选，列中后期档）",
          "- 中期档边界：印度尼西亚 1.97、哥伦比亚 1.93、古巴 1.93（未入选，列起步档）；厄瓜多尔 2.07、多米尼加 2.16、塔吉克斯坦 2.10（入选）",
          "- 起步档边界：危地马拉 1.99、赞比亚 1.85（未入选，列准备档）；叙利亚 2.02、玻利维亚 2.18、洪都拉斯 2.31（入选）", "",
          "## 五、数据来源", "",
          "- 人口：联合国 WPP2024（2024年，全球 8,161,972,574）",
          "- 发电量：Ember（OWID 整理）2024年；乌克兰采用 EIA 2024年 96.9 TWh",
          "- 粗钢产量：世界钢铁协会（worldsteel）2024年国别表；未列入者采用 BGS《World Mineral Production 2020-2024》",
          "- 底图：Natural Earth 110m（ne_110m_countries.geojson），台湾按所属类别着色，南苏丹用 SDS→SSD 别名", "",
          "## 六、与上一版（V1）的变化", "",
          "- 新增两档：成熟工业化国家（4000/400）、工业化中后期国家（3000/300），原\"工业化国家\"（中国2012标准 3641.8 kWh/529.2 kg）取消。",
          "- \"发达国家\"更名为\"后工业化国家\"，以色列列入。",
          "- 中期/起步门槛与中国2000/1990基准基本一致（1000/100≈中国2000，500/50≈中国1990），故这两档名单与V1基本相同。",
          "- 原V1\"工业化国家\"4国（俄/马/沙特/阿联酋）现拆分：俄罗斯、沙特、阿联酋→成熟工业化国家；马来西亚得分2.03，也入成熟档。",
          "- 波兰由V1的工业化中期升入工业化中后期（新标准3000/300达标，2.10）。", "",
          "## 七、2040年推演（另见）", "",
          "本报告为 2024 年实测分类。2040 年推演见 `out/工业化阶段清单_2040.md`、`out/world_industrial_stage_map_2040.png`。",
          "推演以 2024 年分类为基础，按经济发展趋势调整部分国家；未提及国家保持 2024 年等级；",
          "人口采用联合国 WPP2024 中等生育率情景（2040 年全球 91.77 亿）。", "",
          "- 晋级发达国家：中国（2024年成熟工业化国家→后工业化国家）、俄罗斯、土耳其、波兰、沙特阿拉伯、阿联酋、马来西亚、保加利亚、匈牙利、塞尔维亚（台湾地区2024年已按发达国家列入）",
          "- 晋级成熟工业化国家：伊朗、哈萨克斯坦、巴西、智利、乌克兰、罗马尼亚、越南",
          "- 晋级工业化中后期国家：墨西哥、南非、泰国、印度、伊拉克",
          "- 晋级工业化中期国家：印度尼西亚、哥伦比亚、摩洛哥、突尼斯、菲律宾",
          "- 晋级工业化起步国家：21国（巴基斯坦、孟加拉国、尼日利亚、莫桑比克、尼泊尔等）", "",
          "| 类别（2040年） | 国家数 | 总人口 | 占全球总人口比重 |", "|---|---:|---:|---:|",
          "| 后工业化国家（含中国） | 28 | 27.60 亿 | 30.1% |",
          "| 成熟工业化国家 | 7 | 5.24 亿 | 5.7% |",
          "| 工业化中后期国家 | 5 | 19.73 亿 | 21.5% |",
          "| 工业化中期国家 | 16 | 9.91 亿 | 10.8% |",
          "| 工业化起步国家 | 26 | 15.72 亿 | 17.1% |",
          "| 准备工业化国家 | 19 | 10.35 亿 | 11.3% |",
          "| 其他人口不足1000万国家 | — | 3.22 亿 | 3.5% |",
          "| **全球合计** | **101 个实体** | **91.77 亿** | **100.0%** |", "",
          "更新记录：2026-09-23 用户追加——越南→成熟工业化国家；伊拉克→工业化中后期国家；莫桑比克、尼泊尔→工业化起步国家。", ""]

with open(os.path.join(OUT, "report_v2.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print("saved out/report_v2.md", len(lines), "lines")
