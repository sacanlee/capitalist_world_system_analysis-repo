    got = img.getpixel((x, y))
    want = hex2rgb(COLORS[exp])
    ok = got == want
    bad += 0 if ok else 1
    print(f"{name:<10} 像素{got} 期望{want}({exp}) {'OK' if ok else '★不一致'}")
